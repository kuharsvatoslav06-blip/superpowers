// Voice-over generator: synthesizes every line of the script with an offline TTS engine (Festival + MBROLA us2),
// post-processes it with ffmpeg and writes build/voice/<id>.wav plus src/generated/voice.js (durations for subtitles).
// To use a real voice (e.g. ElevenLabs): drop files named <line id>.wav/.mp3 into voice/ — they take precedence.
import fs from 'node:fs'; import path from 'node:path'; import { execFileSync } from 'node:child_process';
import { LINES, sceneById } from '../src/story/script.js';
import { ROOT } from './server.js';

const OUT = path.join(ROOT, 'build/voice'); const TMP = path.join(ROOT, 'build/tmp'); const CUSTOM = path.join(ROOT, 'voice');
fs.mkdirSync(OUT, { recursive: true }); fs.mkdirSync(TMP, { recursive: true });
const hasFestival = (() => { try { execFileSync('which', ['festival']); return true; } catch { return false; } })();
const clean = s => s.replace(/\*/g, '').replace(/"/g, '').replace(/—/g, ', ');
const ff = args => execFileSync('ffmpeg', ['-loglevel', 'error', '-y', ...args]);
const dur = f => +execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString().trim();

// Voice character per kind: pitch factor (asetrate), tempo, extra filters
const STYLE = {
  nar: { voice: 'us2_mbrola', stretch: 0.97, pitch: 1.07, tempo: 1.0, fx: 'aecho=0.8:0.5:40:0.12' },
  dia: { voice: 'us2_mbrola', stretch: 0.92, pitch: 1.12, tempo: 1.03, fx: '' },
  read: { voice: 'us2_mbrola', stretch: 1.05, pitch: 1.08, tempo: 0.98, fx: 'aecho=0.8:0.6:60:0.2' },
  whisper: { voice: 'us2_mbrola', stretch: 1.0, pitch: 1.1, tempo: 1.0, fx: 'highpass=f=300,volume=0.75' },
  entity: { voice: 'kal_diphone', stretch: 1.25, pitch: 0.72, tempo: 0.95, fx: 'aecho=0.8:0.7:120|260:0.4|0.25,lowpass=f=3500' },
};
const manifest = {};
for (const l of LINES) {
  const out = path.join(OUT, l.id + '.wav'); const st = STYLE[l.kind] || STYLE.dia;
  const custom = ['.wav', '.mp3', '.m4a', '.flac'].map(e => path.join(CUSTOM, l.id + e)).find(f => fs.existsSync(f));
  if (custom) { const extra = l.kind === 'entity' ? 'aresample=48000,asetrate=40800,aresample=48000,atempo=1.0,aecho=0.8:0.7:120|260:0.35|0.2,' : ''; ff(['-i', custom, '-af', extra + 'silenceremove=start_periods=1:start_threshold=-50dB:stop_periods=-1:stop_threshold=-50dB:stop_duration=0.3,loudnorm=I=-16:TP=-1.5:LRA=7', '-ac', '1', '-ar', '48000', out]); }
  else {
    if (!hasFestival) { console.error('festival not installed: sudo apt-get install festival festvox-us2 (or put recordings into voice/)'); process.exit(1); }
    const raw = path.join(TMP, l.id + '.raw.wav'); const scm = path.join(TMP, l.id + '.scm');
    const text = clean(l.text).replace(/\\/g, '');
    fs.writeFileSync(scm, `(voice_${st.voice})\n(Parameter.set 'Duration_Stretch ${st.stretch})\n(set! u (SayText "${text.replace(/"/g, '')}"))\n(utt.save.wave u "${raw}" 'riff)\n`);
    execFileSync('festival', ['-b', scm], { stdio: ['ignore', 'ignore', 'ignore'] });
    const sr = 16000; const af = [`asetrate=${Math.round(sr * st.pitch)}`, 'aresample=48000', `atempo=${(st.tempo / st.pitch).toFixed(4)}`, 'highpass=f=90', 'lowpass=f=7800',
      'equalizer=f=2500:t=q:w=1:g=3', 'acompressor=threshold=-20dB:ratio=3:attack=5:release=80', st.fx,
      'silenceremove=start_periods=1:start_threshold=-45dB:stop_periods=-1:stop_threshold=-45dB:stop_duration=0.25', 'loudnorm=I=-16:TP=-1.5:LRA=7'].filter(Boolean).join(',');
    ff(['-i', raw, '-af', af, '-ac', '1', '-ar', '48000', out]);
  }
  manifest[l.id] = { dur: +dur(out).toFixed(3) };
}
fs.writeFileSync(path.join(ROOT, 'src/generated/voice.js'), '// Generated by tools/tts.js — voice line durations (seconds).\nexport default ' + JSON.stringify(manifest, null, 1) + ';\n');
// timing report: lines must not overlap the next line or run past the scene end
let warn = 0;
const byScene = {}; for (const l of LINES) (byScene[l.scene] ||= []).push(l);
for (const [sc, ls] of Object.entries(byScene)) ls.forEach((l, i) => {
  const end = l.t + manifest[l.id].dur; const next = ls[i + 1]?.t ?? sceneById[sc].dur;
  if (end > next - 0.1) { warn++; console.warn(`WARN ${l.id}: ends at ${end.toFixed(2)}s but next cue at ${next}s (over by ${(end - next).toFixed(2)}s)`); }
});
console.log(`voice: ${LINES.length} lines -> build/voice, ${warn} timing warnings`);
